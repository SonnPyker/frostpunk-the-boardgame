// Test helper: a fully initialised, empty GameState (no tiles, decks, tokens). Unit tests build the scenario they need on top.
import type { GameConfig, GameState } from './types';
import { seedRng } from './rng';

const COLORS = ['#c0392b', '#2e86c1', '#27ae60', '#d4ac0d'];

export function blankConfig(over: Partial<GameConfig> = {}): GameConfig {
  return {
    scenario: 'crater',
    society: 1,
    difficulty: 'normal',
    mode: 'solo',
    players: [{ name: 'Captain' }],
    seed: 1,
    extraPack: false,
    ...over,
  };
}

