    Dice4.setValue(Law4)
    wait(0.4)

    -- Loop and move the appropriate law on top of the basic Law
    for i = 1, #LawCards do
        if Law1 == i or Law2 == i or Law3 == i or Law4 == i then
            for _, object in ipairs(LawCards[i]) do
                if object.name == "Deck" then
                    object.setPositionSmooth(TblLawDeckPos[LawIndex])
                else
                    object.setPositionSmooth(TblLawCardPos[LawIndex])
                end
                wait(0.5)
            end
            LawIndex = LawIndex + 1
        end
    end
end

function SetupTechCard()
    broadcastToAll('Setting up Technology Cards...')
    local Deck = getObjectFromGUID(TechDeck_GUID)
    local Token = {}
    local Card
    for i=1, #TblTechToken_GUID do
        Token[i] = getObjectFromGUID(TblTechToken_GUID[i])
    end

    Deck.randomize()

    for i=1, #Token do
        if SetupBoardNumber == 2 and i==1 then
            -- Frozen Grove: Steam Hub card face up in slot 1; the other slots are drawn at random from all
            -- remaining Technology cards (no exclusions; Scenario Book Frozen Grove, Additional setup step 2).
            for _, containedObject in ipairs(Deck.getObjects()) do
                if containedObject.guid == TechCardSteamHub_GUID then
                    Card = Deck.takeObject({ position = TblTechCardPos[i], rotation = TechCardRot, index = containedObject.index })
                    wait(0.2)
                    break -- Stop iterating
                end
            end
        else
            for _, containedObject in ipairs(Deck.getObjects()) do
                if containedObject.guid == TechCardSteamHub_GUID then
                    Card = Deck.takeObject({ position = Scenario1UnusedStormCardPos, rotation = {0,180,180}, index = containedObject.index })
                    wait(0.2)
                    break -- Stop iterating
                end
            end
            Card = Deck.takeObject({ position = TblTechCardPos[i], rotation = TechCardRot })
        end

        Card.setLock(true)
        wait(0.5)
        Token[i].setPositionSmooth(TblTechTokenPos[i], false, false)
        Token[i].setRotationSmooth(TechCardRot, false, false)
        wait(0.2)
    end

    Deck.setPositionSmooth(Scenario1UnusedStormCardPos, false, false)
    Deck.setRotationSmooth({0,180,180}, false, false)
end

