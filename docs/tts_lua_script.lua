function Click_Setup()
    local seatedPlayers = getSeatedPlayers()
    local SocietyZone = getObjectFromGUID(ChooseSocietyZone_GUID)
    local NumberOfItemInZone = 0
    CurrentSociety = ""

    for i, object in ipairs(SocietyZone.getObjects()) do
        NumberOfItemInZone = i
        CurrentSociety_GUID = object.guid
    end

    for refSociety, ref in pairs(Society) do
        if CurrentSociety_GUID == Society[refSociety].Card_GUID then
            CurrentSociety = Society[refSociety]
        end
    end

    if NumberOfItemInZone < 1 and SetupSocietyLevel == 0 then
        broadcastToAll("Please choose one of the Society and place it in the Choose Society Zone")
    elseif NumberOfItemInZone > 1 then
        broadcastToAll("Please make sure there is only one item in the Choose Society Zone")
    elseif #seatedPlayers == 0 then
        broadcastToAll("Please choose one of the available colors")
    elseif SetupBoardNumber == 0 then
        broadcastToAll("Please Select a Board Setup")
    elseif CurrentSociety == "" and SetupSocietyLevel == 0 then
        broadcastToAll("The item in the Choose Society Zone is not a Society")
    else
        startLuaCoroutine(Global, "SetupGame")
    end
end

