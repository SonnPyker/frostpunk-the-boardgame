                        TokenRess = 2
                    end
                    TblWallRessPresent[3] = 1
                    wait(0.3)
                    break
                end
            end
        end
        for i=1, #TblWallTokenPos do
            if TokenCounter == 1 then
                Token = bag.takeObject({ position = TblWallTokenPos[4], rotation={0,180,0} })
                Token.setLock(true)
                if Token.guid == WallRessBlank1_GUID or Token.guid == WallRessBlank2_GUID or Token.guid == WallRessBlank3_GUID then
                    Token.destruct()
                elseif TokenRess == 1 and (Token.guid == WallRessWood1_GUID or Token.guid == WallRessWood2_GUID) then
                    Token.destruct()
                elseif TokenRess == 2 and (Token.guid == WallRessCoal1_GUID or Token.guid == WallRessCoal2_GUID) then
                    Token.destruct()
                else
                    TokenCounter = TokenCounter + 1
                    TblWallRessPresent[4] = 1
                    wait(0.3)
                    break
                end
            end
        end
        destroyObject(bag)
    end
