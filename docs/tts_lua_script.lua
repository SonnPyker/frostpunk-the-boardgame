function RetrieveWorker()

    WorkerCounter = 0
    EngineerCounter = 0
    ChildCounter = 0
    AutomatonCounter = 0
    RetrieveWorkerByZone(BoardZoneMain_GUID)
    RetrieveWorkerByZone(BoardZoneLower_GUID)
    RetrieveWorkerByZone(BoardZoneUpper_GUID)
    RetrieveWorkerByZone(ConstructionZone_GUID)
    RetrieveWorkerByZone(SnowRemovalZone_GUID)

    return 1
end

function RetrieveWorkerByZone(Zone_GUID)
    local Zone = getObjectFromGUID(Zone_GUID)
    for _, obj in ipairs(Zone.getObjects()) do
        if obj.getName() == "Worker" then

            obj.setPositionSmooth(Vector(WorkerPos) + Vector(0, 0, -WorkerOffsetZ*WorkerCounter), false, false)
            obj.setRotationSmooth({0,180,0}, false, false)

            WorkerCounter = WorkerCounter + 1
            wait(0.2)
        end

        if obj.getName() == "Engineer" then

            obj.setPositionSmooth(Vector(EngineerPos) + Vector(0, 0, -WorkerOffsetZ*EngineerCounter), false, false)
            obj.setRotationSmooth({0,0,0}, false, false)

            EngineerCounter = EngineerCounter + 1
            wait(0.2)
        end

        if obj.getName() == "Child" or obj.getName() == "Child Worker" or obj.getName() == "Child Engineer" then

            obj.setPositionSmooth(Vector(ChildPos) + Vector(0, 0, -WorkerOffsetZ*ChildCounter), false, false)
            obj.setRotationSmooth({0,180,0}, false, false)

            ChildCounter = ChildCounter + 1
            wait(0.2)
        end

        if obj.getName() == "Automaton" then

            obj.setPositionSmooth(Vector(AutomatonPos) + Vector(0, 0, -WorkerOffsetZ*AutomatonCounter), false, false)
            obj.setRotationSmooth({0,180,0}, false, false)

            AutomatonCounter = AutomatonCounter + 1
            wait(0.2)
        end
    end
end


function MoveToken(Token_GUID, TokenPos, TokenValue, Offset)
    local Token = getObjectFromGUID(Token_GUID)
    local TokenNewPos = Vector(TokenPos) + Vector(Offset*TokenValue, 0, 0)

    Token.setPositionSmooth(TokenNewPos, false, false)
    wait(0.3)
end

function wait(time)
    local start = os.time()
    repeat
        coroutine.yield(0)
    until os.time() > start + time
end

