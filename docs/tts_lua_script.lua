function PlaceMainTile(MainTilePos)
    local MainTile = getObjectFromGUID(CenterTile_GUID)
    local Generator = getObjectFromGUID(Generator_GUID)
    local CookHouseTile = getObjectFromGUID(BuildingCookHouse_GUID)
    local WoodBag = getObjectFromGUID(WoodBag_GUID)
    local CoalBag = getObjectFromGUID(CoalBag_GUID)

    MainTile.setPositionSmooth(MainTilePos, false, false)
    MainTile.setRotationSmooth(MainTile_Rot, false, false)
    MainTile.setLock(true)
    wait(0.3)

    Generator.setPositionSmooth(Vector(MainTilePos) + Vector(MainTile_RelGeneratorPos), false, false)
    Generator.setRotationSmooth(MainTile_GeneratorRot, false, false)
    Generator.setLock(true)
    wait(0.3)

    CookHouseTile.setPositionSmooth(Vector(MainTilePos) + Vector(MainTile_RelCookHouseTilePos), false, false)
    CookHouseTile.setRotationSmooth(MainTile_CookHouseTileRot, false, false)
    CookHouseTile.setLock(true)
    wait(0.3)

    for i=1, #MainTile_TblWoodPos do
        WoodBag.takeObject({position = Vector(MainTilePos) + Vector(MainTile_TblWoodPos[i]), rotation = {0,180,0} })
        wait(0.2)
    end
    for i=1, #MainTile_TblCoalPos do
        CoalBag.takeObject({position = Vector(MainTilePos) + Vector(MainTile_TblCoalPos[i]), rotation = {0,0,0} })
        wait(0.2)
    end
end

