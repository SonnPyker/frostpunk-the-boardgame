function PlaceTile(Index, Deck, TblTilePos, RessEnabled)
    local Tile
    local TileGUID
    local TileNbr

    local TreeBag = getObjectFromGUID(TreeBag_GUID)
    local WoodBag = getObjectFromGUID(WoodBag_GUID)
    local CoalBag = getObjectFromGUID(CoalBag_GUID)
    local CoreBag = getObjectFromGUID(CoreBag_GUID)

    local FoodToken = getObjectFromGUID(FoodToken_GUID)

    Tile = Deck.takeObject({ position =TblTilePos[Index], rotation={0,180,0} })
    TileGUID = Tile.getGUID()
    wait(0.4)
    Tile.setLock(true)

    for i = 1, #TblTile do
        if TileGUID == TblTile[i].GUID then
            TileNbr = i
            break
        end
    end

    if RessEnabled then
        for i, Ress in ipairs(TblTile[TileNbr].Ress) do
            -- Top Tree
            if i==1 and Ress > 0 then
                for i=1, Ress do
                    TreeBag.takeObject({ position = Vector(TblTilePos[Index]) + Vector(TblTileTopRessVecPos[i]), rotation={0,0,0} })
                    wait(0.2)
            end
            -- Bottom Tree
            elseif i==2 and Ress > 0 then
                for i=1, Ress do
                    TreeBag.takeObject({ position = Vector(TblTilePos[Index]) + Vector(TblTileBotRessVecPos[i]), rotation={0,0,0} })
                    wait(0.2)
                end
            -- Top Wood
            elseif i==3 and Ress > 0 then
                for i=1, Ress do
                    WoodBag.takeObject({ position = Vector(TblTilePos[Index]) + Vector(TblTileTopRessVecPos[i]), rotation={0,180,0} })
                    wait(0.2)
                end
            -- Bottom Wood
            elseif i==4 and Ress > 0 then
                for i=1, Ress do
                    WoodBag.takeObject({ position = Vector(TblTilePos[Index]) + Vector(TblTileBotRessVecPos[i]), rotation={0,180,0} })
                    wait(0.2)
                end
            -- Top Coal
            elseif i==5 and Ress > 0 then
                for i=1, Ress do
                    CoalBag.takeObject({ position = Vector(TblTilePos[Index]) + Vector(TblTileTopRessVecPos[i]), rotation={0,0,0} })
                    wait(0.2)
                end
            -- Bottom Coal
            elseif i==6 and Ress > 0 then
                for i=1, Ress do
                    CoalBag.takeObject({ position = Vector(TblTilePos[Index]) + Vector(TblTileBotRessVecPos[i]), rotation={0,0,0} })
                    wait(0.2)
                end
            -- Top Core
            elseif i==7 and Ress > 0 then
                for i=1, Ress do
                    CoreBag.takeObject({ position = Vector(TblTilePos[Index]) + Vector(TblTileTopRessVecPos[i]) + Vector({-0.25, 0, -0.15}), rotation={0,180,0} })
                    wait(0.2)
                end
            -- Bottom Core
            elseif i==8 and Ress > 0 then
                for i=1, Ress do
                    CoreBag.takeObject({ position = Vector(TblTilePos[Index]) + Vector(TblTileBotRessVecPos[i]) + Vector({-0.25, 0, 0.15}), rotation={0,180,0} })
                    wait(0.2)
                end
            -- Food Token
            elseif i==9 and Ress > 0 then
                if FoodTokenValue == 0 then
                    FoodTokenValue = FoodTokenValue + Ress
                    MoveToken(FoodToken_GUID, FoodTokenPos1, FoodTokenValue-1, Token_Movement)
                else
                    FoodTokenValue = FoodTokenValue + Ress
                    MoveToken(FoodToken_GUID, FoodTokenPos1, FoodTokenValue-1, Token_Movement)
                end

                wait(0.2)
            end
        end
    end

end

